def main():
    wb = Workbook()
    ws = wb.active
    ws.title = "미팅후 반영 가이드"
    ws.merge_cells("A1:D1")
    ws["A1"] = "10/27 미팅 답변별 제안서 반영 가이드 (내부용 · 제출 제외)"
    ws["A1"].font = Font(name=FONT, size=14, bold=True)
    head = ["미팅 질문", "답변 경우", "제안서 반영 내용", "반영 위치 (쪽)"]
    widths = [22, 24, 70, 28]
    box = Border(*(Side(style="thin", color="999999"),) * 4)
    for i, (h, w) in enumerate(zip(head, widths)):
        c = ws.cell(row=3, column=i + 1, value=h)
        c.font = Font(name=FONT, size=10, bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="1F4E9A")
        c.alignment = Alignment(horizontal="center", vertical="center")
        c.border = box
        ws.column_dimensions["ABCD"[i]].width = w
    for r, row in enumerate(ROWS, start=4):
        for i, v in enumerate(row):
            c = ws.cell(row=r, column=i + 1, value=v)
            c.font = Font(name=FONT, size=10)
            c.alignment = Alignment(vertical="center", wrap_text=True)
            c.border = box
    ws.freeze_panes = "A4"
    set_xlsx_author(wb)
    out = HERE / "미팅후_반영가이드.xlsx"
    wb.save(out)
    print("저장:", out, len(ROWS), "행")


if __name__ == "__main__":
    main()
